    const contents = document.querySelectorAll('.pathway-tab-content');
    contents.forEach(content => {
        content.style.display = 'none';
        content.classList.remove('active');
    });

    // 2. Remove 'active' class from all buttons
    const buttons = document.querySelectorAll('.pathway-tab-btn');
    buttons.forEach(btn => {
        btn.classList.remove('active');
    });

    // 3. Show the specific tab content
    document.getElementById(tabId).style.display = 'block';
    // Small delay to allow CSS animation to trigger if needed, or just add class
    setTimeout(() => {
        document.getElementById(tabId).classList.add('active');
    }, 10);

